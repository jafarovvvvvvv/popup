namespace Popup.Notch;

/// <summary>
/// Во что развёрнута панель прямо сейчас.
///
/// Состояний стало три, а не два. Между «свёрнута» и «раскрыта» появилось
/// третье — узкая полоска, которую панель показывает, пока в системе что-то
/// происходит: идёт запись, крутится расшифровка. Оно нужно потому, что такие
/// вещи надо видеть, не наводя мышь, и при этом они не стоят шестисот точек
/// раскрытой панели поверх работы.
/// </summary>
public enum PanelState
{
    /// <summary>Полоска в шесть точек. Панель в покое.</summary>
    Collapsed,

    /// <summary>Компактная строка состояния: что-то идёт прямо сейчас.</summary>
    Activity,

    /// <summary>Полная панель со вкладками.</summary>
    Expanded,
}
